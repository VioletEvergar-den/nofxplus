// drawer 位图文本绘制器
type drawer struct {
	img *image.RGBA
}

// text 在 (x,y) 绘制 ASCII 文本（scale 为像素放大倍数），返回结束 x 坐标
func (d *drawer) text(x, y int, s string, scale int, col color.RGBA) int {
	return d.textClip(x, y, s, scale, col, imgW)
}

// textClip 同 text，但超出 maxX 时截断（用于右轴标签防溢出）
func (d *drawer) textClip(x, y int, s string, scale int, col color.RGBA, maxX int) int {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for i := 0; i < len(s); i++ {
		ch := s[i]
		glyph, ok := font5x7[ch]
		if !ok {
			glyph = font5x7['?']
		}
		for row := 0; row < 7; row++ {
			bits := glyph[row]
			for px5 := 0; px5 < 5; px5++ {
				if bits&(1<<(4-px5)) != 0 {
					for sy := 0; sy < scale; sy++ {
						for sx := 0; sx < scale; sx++ {
							px, py := cx+px5*scale+sx, y+row*scale+sy
							if px < maxX && px < imgW && py >= 0 && py < imgH {
								d.img.Set(px, py, col)
							}
						}
					}
				}
			}
		}
		cx += (5 + 1) * scale
	}
	return cx
}
